module Тесты

open System
open Xunit
open GAXT.NET

let проверитьПрограмму (программа: string) (ожидаемыйВывод: string) =
    let консоль = new System.IO.StringWriter()
    let интерпретатор = Программа.создатьИнтерпретатор консоль
    let результат = Программа.интерпретироватьСтроку интерпретатор программа
    Assert.Equal(ожидаемыйВывод, консоль.ToString())

[<Fact>]
let ``Hello, world!`` () =
    проверитьПрограмму "\"Hello, world!'\\n\"~[$~]!" "Hello, world!\n"

[<Fact>]
let ``Арифметика`` () =
    проверитьПрограмму "123++?!" "6"

[<Fact>]
let ``Конкатенация цифр`` () =
    проверитьПрограмму "12_3_?!" "123"

[<Fact>]
let ``Присваивание`` () =
    проверитьПрограмму "a42_:#?!" "42"

[<Fact>]
let ``Математика на VarStack`` () =
    проверитьПрограмму "a3:b4:#+#?!" "7"

[<Fact>]
let ``Значение переменной в CalcStack`` () =
    проверитьПрограмму "a7:0#:#?!" "7"

[<Fact>]
let ``Условие (then)`` () =
    проверитьПрограмму "23<{40_|50_}?!" "40"

[<Fact>]
let ``Условие (else)`` () =
    проверитьПрограмму "32<{40_|50_}?!" "50"

[<Fact>]
let ``Цикл`` () =
    проверитьПрограмму "5[?1-]!" "54321"
