module GAXT.NET.Программа

    open System.IO

    type Токен =
        | СтроковыйЛитерал of string
        | ВстроеннаяФункция of char
        | Команда of char
        | Цифра of char
        | Символ of char

    type Интерпретатор =
        {
            консоль: System.IO.TextWriter
            активныйСтек: цел
            mutable текущееЗначение: цел option
            стекВычислений: System.Collections.Generic.Stack<int>
            стекИменПеременных: System.Collections.Generic.Stack<int>
            стекЦиклов: System.Collections.Generic.Stack<int>
        }

    let создатьИнтерпретатор (консоль: System.IO.TextWriter) =
        { 
            консоль = консоль
            активныйСтек = 0
            текущееЗначение = None
            стекВычислений = System.Collections.Generic.Stack<int>()
            стекИменПеременных = System.Collections.Generic.Stack<int>()
            стекЦиклов = System.Collections.Generic.Stack<int>()
        }

    let положитьНаСтек (интерпретатор: Интерпретатор) (значение: int) =
        if интерпретатор.активныйСтек = 0 then
            интерпретатор.стекВычислений.Push(значение)
        else
            интерпретатор.стекИменПеременных.Push(значение)

    let забратьСоСтека (интерпретатор: Интерпретатор) =
        if интерпретатор.активныйСтек = 0 then
            интерпретатор.стекВычислений.Pop()
        else
            интерпретатор.стекИменПеременных.Pop()

    let посмотретьНаСтек (интерпретатор: Интерпретатор) =
        let (естьЗначение, значение) = 
            if интерпретатор.активныйСтек = 0 then
                интерпретатор.стекВычислений.TryPeek() 
            else
                интерпретатор.стекИменПеременных.TryPeek()
        if естьЗначение then Some значение else None

    let сообщитьПроОшибку интерпретатор сообщение =
        интерпретатор.консоль.WriteLine("[Ошибка]: " + сообщение)
        raise (System.InvalidOperationException(сообщение))

    let private разделитьНаТокены (интерпретатор: Интерпретатор) (программа: StreamReader) : Токен seq =
        seq {
            let mutable текущийСимвол = программа.Read()
            while текущийСимвол <> -1 do
                let символ = char текущийСимвол
                match символ with
                | '"' ->
                    // Начало строкового литерала
                    let строка = System.Text.StringBuilder()
                    let mutable экранирование = false
                    let mutable двойноеЭкранирование = false
                    текущийСимвол <- программа.Read()
                    while текущийСимвол <> -1 && char текущийСимвол <> '"' do
                        if не экранирование then
                            if char текущийСимвол <> '\'' then
                                строка.Append(char текущийСимвол) |> ignore
                            else
                                экранирование <- true
                        else
                            if not двойноеЭкранирование then
                                if char текущийСимвол = '\\' then
                                    двойноеЭкранирование <- true
                                else
                                    строка.Append(char текущийСимвол) |> ignore
                                    экранирование <- false
                            else
                                if char текущийСимвол = 'n' then
                                    строка.Append('\n') |> ignore
                                elif char текущийСимвол = 't' then
                                    строка.Append('\t') |> ignore
                                else
                                    // Неспецифицированное поведение.
                                    строка.Append('\\') |> ignore
                                    строка.Append(char текущийСимвол) |> ignore
                                двойноеЭкранирование <- false
                        текущийСимвол <- программа.Read()
                    yield СтроковыйЛитерал(строка.ToString())
                // 5.1 Данные
                | символ when символ >= '0' && символ <= '9' -> yield Цифра(символ)
                | символ when символ >= 'a' && символ <= 'z' -> yield Символ(символ)
                // 5.2 Математика
                | '+' | '-' | '*' | '/' | '_' 
                // 5.3 Логика
                | '`' | '<' | '=' | '>'
                // 5.4 Печать
                | '?' | '$'
                // 5.5 Стек
                | ':' | ';' | '~' | '%' | '#' 
                // 5.6 Поток управления
                | '{' | '|' | '}' | '\\' | '^' | '!'
                // 5.7 Макросы
                | '(' | ')' | '@'
                // 5.8 Циклы
                | '[' | ']'
                // 5.9 Метки
                | '.' | ','
                    -> yield Команда(символ)
                // 5.12 Функции A–Z
                | символ when символ >= 'A' && символ <= 'Z' -> yield ВстроеннаяФункция(символ)
                | _ -> 
                    сообщитьПроОшибку интерпретатор (sprintf "Неизвестный символ: %c" символ)
                    yield Символ(символ)
                текущийСимвол <- программа.Read()
        }

    let интерпретировать (интерпретатор: Интерпретатор) (программа: StreamReader) =
        // Здесь можно добавить логику интерпретации программы
        // Для примера просто выводим программу в консоль
        let токены = разделитьНаТокены интерпретатор программа |> Seq.toList
        let mutable индексТокена = 0 
        while индексТокена < токены.Length do
            let токен = токены.[индексТокена]
        //for токен in разделитьНаТокены интерпретатор программа do
            match токен with
            | СтроковыйЛитерал(строка) -> 
                for i = строка.Length - 1 downto 0 do
                    let символ = строка.[i]
                    положитьНаСтек интерпретатор (int символ)
                положитьНаСтек интерпретатор строка.Length
                индексТокена <- индексТокена + 1
            | ВстроеннаяФункция(символ) -> 
                raise (System.InvalidOperationException("Встроенная функция: " + символ.ToString()))
            | Команда(символ) -> 
                let следующийИндекс = 
                    match символ with
                    // 5.2 Математика
                    | '+' -> 
                        let b = забратьСоСтека интерпретатор
                        let a = забратьСоСтека интерпретатор
                        положитьНаСтек интерпретатор (a + b)
                        None
                    | '-' -> 
                        let b = забратьСоСтека интерпретатор
                        let a = забратьСоСтека интерпретатор
                        положитьНаСтек интерпретатор (a - b)
                        None
                    | '*' -> 
                        let b = забратьСоСтека интерпретатор
                        let a = забратьСоСтека интерпретатор
                        положитьНаСтек интерпретатор (a * b)
                        None
                    | '/' -> 
                        let b = забратьСоСтека интерпретатор
                        let a = забратьСоСтека интерпретатор
                        положитьНаСтек интерпретатор (a / b)
                        None
                    | '_' -> 
                        let b = забратьСоСтека интерпретатор
                        let a = забратьСоСтека интерпретатор
                        let результат =
                            if (a > 0 && b > 0) || (a < 0 && b < 0) then
                                a.ToString() + b.ToString() |> int
                            elif (a > 0 && b < 0) || (a > 0 && b < 0) then
                                -(a.ToString() + b.ToString() |> int)
                            else
                                (a * 10 + b)
                        положитьНаСтек интерпретатор результат
                        None
                    // 5.4 Печать
                    | '?' -> 
                        let текущееЗначение = посмотретьНаСтек интерпретатор |> Option.defaultValue 0
                        интерпретатор.консоль.Write(текущееЗначение)
                        None
                    | '$' -> 
                        let текущееЗначение = посмотретьНаСтек интерпретатор |> Option.defaultValue 0
                        интерпретатор.консоль.Write(char текущееЗначение)
                        None
                    // 5.5 Стек
                    | '~' -> 
                        интерпретатор.текущееЗначение <- Some (забратьСоСтека интерпретатор)
                        None                        
                    // 5.6 Поток управления
                    | '!' -> 
                        Some System.Int32.MaxValue
                    // 5.8 Циклы
                    | '[' -> 
                        //интерпретатор.стекЦиклов.Push(int программа.BaseStream.Position)
                        интерпретатор.стекЦиклов.Push (индексТокена + 1)
                        None
                    | ']' -> 
                        let текущееЗначение = посмотретьНаСтек интерпретатор |> Option.defaultValue 0
                        if текущееЗначение = 0 then
                            интерпретатор.стекЦиклов.Pop() |> игноровать
                            None
                        else
                            let позиция = интерпретатор.стекЦиклов.Peek()
                            //программа.BaseStream.Seek(int64 позиция, SeekOrigin.Begin) |> игноровать
                            Some позиция
                    | _ ->
                        интерпретатор.консоль.WriteLine("Команда: " + символ.ToString())
                        None
                индексТокена <- следующийИндекс |> Option.defaultValue (индексТокена + 1)
            | Цифра(число) -> 
                положитьНаСтек интерпретатор (int число - int '0')
                индексТокена <- индексТокена + 1
            | Символ(символ) -> 
                положитьНаСтек интерпретатор (int символ)
                индексТокена <- индексТокена + 1

    let интерпретироватьСтроку (интерпретатор: Интерпретатор) (программа: string) =
        интерпретировать интерпретатор (new StreamReader(new MemoryStream(System.Text.Encoding.UTF8.GetBytes(программа))))

    [<EntryPoint>]
    let main argv =
        printfn "Hello from F#"
