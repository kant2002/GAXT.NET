module GAXT.NET.Программа

    open System.IO

    type Токен =
        | СтроковыйЛитерал of строка
        | ВстроеннаяФункция of char
        | Команда of char
        | Цифра of char
        | Символ of char

    type Кадр =
        | Цикл of цел
        | Условие of цел * bool

    type Интерпретатор =
        {
            консоль: System.IO.TextWriter
            mutable активныйСтек: цел
            mutable текущееЗначение: цел option
            стекВычислений: System.Collections.Generic.Stack<цел>
            стекИменПеременных: System.Collections.Generic.Stack<цел>
            стекКадров: System.Collections.Generic.Stack<Кадр>
            mutable переменные: цел array
        }

    let создатьИнтерпретатор (консоль: System.IO.TextWriter) =
        { 
            консоль = консоль
            активныйСтек = 0
            текущееЗначение = None
            стекВычислений = System.Collections.Generic.Stack<цел>()
            стекИменПеременных = System.Collections.Generic.Stack<цел>()
            стекКадров = System.Collections.Generic.Stack<Кадр>()
            переменные = Array.create 26 0
        }

    let положитьНаСтек (интерпретатор: Интерпретатор) (значение: цел) =
        if интерпретатор.активныйСтек = 0 then
            интерпретатор.стекВычислений.Push(значение)
        else
            интерпретатор.стекИменПеременных.Push(значение)

    let забратьСоСтека (интерпретатор: Интерпретатор) =
        if интерпретатор.активныйСтек = 0 then
            интерпретатор.стекВычислений.Pop()
        else
            let код = интерпретатор.стекИменПеременных.Pop()
            интерпретатор.переменные.[код - int 'a']

    let посмотретьНаСтек (интерпретатор: Интерпретатор) =
        let (естьЗначение, значение) = 
            if интерпретатор.активныйСтек = 0 then
                интерпретатор.стекВычислений.TryPeek() 
            else
                let (естьЗначение, код) = интерпретатор.стекИменПеременных.TryPeek()
                if естьЗначение then
                    (true, интерпретатор.переменные.[код - int 'a'])
                else
                    (false, 0)
        if естьЗначение then Some значение else None

    let сообщитьПроОшибку интерпретатор сообщение =
        интерпретатор.консоль.WriteLine("[Ошибка]: " + сообщение)
        raise (System.InvalidOperationException(сообщение))

    let private разделитьНаТокены (интерпретатор: Интерпретатор) (программа: StreamReader) : Токен seq =
        seq {
            let mutable текущийСимвол = программа.Read()
            while текущийСимвол <> -1 do
                let символ = char текущийСимвол
                match символ with
                | '"' ->
                    // Начало строкового литерала
                    let строка = System.Text.StringBuilder()
                    let mutable экранирование = false
                    let mutable двойноеЭкранирование = false
                    текущийСимвол <- программа.Read()
                    while текущийСимвол <> -1 && char текущийСимвол <> '"' do
                        if не экранирование then
                            if char текущийСимвол <> '\'' then
                                строка.Append(char текущийСимвол) |> ignore
                            else
                                экранирование <- true
                        else
                            if not двойноеЭкранирование then
                                if char текущийСимвол = '\\' then
                                    двойноеЭкранирование <- true
                                else
                                    строка.Append(char текущийСимвол) |> ignore
                                    экранирование <- false
                            else
                                if char текущийСимвол = 'n' then
                                    строка.Append('\n') |> ignore
                                elif char текущийСимвол = 't' then
                                    строка.Append('\t') |> ignore
                                else
                                    // Неспецифицированное поведение.
                                    строка.Append('\\') |> ignore
                                    строка.Append(char текущийСимвол) |> ignore
                                двойноеЭкранирование <- false
                        текущийСимвол <- программа.Read()
                    yield СтроковыйЛитерал(строка.ToString())
                // 5.1 Данные
                | символ when символ >= '0' && символ <= '9' -> yield Цифра(символ)
                | символ when символ >= 'a' && символ <= 'z' -> yield Символ(символ)
                // 5.2 Математика
                | '+' | '-' | '*' | '/' | '_' 
                // 5.3 Логика
                | '`' | '<' | '=' | '>'
                // 5.4 Печать
                | '?' | '$'
                // 5.5 Стек
                | ':' | ';' | '~' | '%' | '#' 
                // 5.6 Поток управления
                | '{' | '|' | '}' | '\\' | '^' | '!'
                // 5.7 Макросы
                | '(' | ')' | '@'
                // 5.8 Циклы
                | '[' | ']'
                // 5.9 Метки
                | '.' | ','
                    -> yield Команда(символ)
                // 5.12 Функции A–Z
                | символ when символ >= 'A' && символ <= 'Z' -> yield ВстроеннаяФункция(символ)
                | _ -> 
                    сообщитьПроОшибку интерпретатор (sprintf "Неизвестный символ: %c" символ)
                    yield Символ(символ)
                текущийСимвол <- программа.Read()
        }

    let интерпретировать (интерпретатор: Интерпретатор) (программа: StreamReader) =
        // Здесь можно добавить логику интерпретации программы
        // Для примера просто выводим программу в консоль
        let токены = разделитьНаТокены интерпретатор программа |> Seq.toList

        let пропуститьКадрУсловия = fun индексТокена ->
            let mutable счетчик = 0
            let mutable новыйИндекс = (0, false)
            for i = индексТокена + 1 to токены.Length do
                if (not (snd новыйИндекс)) then
                    let токен = токены[i]
                    if токен = Команда('}') then
                        if счетчик = 0 then
                            новыйИндекс <- (i + 1, true)
                        else
                            счетчик <- счетчик - 1
                    elif токен = Команда('|') then
                        if счетчик = 0 then
                            raise (System.InvalidOperationException("Неправильное использование '|' без соответствующего '{'"))
                    elif токен = Команда('{') then
                        счетчик <- счетчик + 1
                    else
                        ()
            if snd новыйИндекс then
                Some (fst новыйИндекс)
            else
                None

        let mutable индексТокена = 0 
        while индексТокена < токены.Length do
            let токен = токены.[индексТокена]
            match токен with
            | СтроковыйЛитерал(строка) -> 
                for i = строка.Length - 1 downto 0 do
                    let символ = строка.[i]
                    положитьНаСтек интерпретатор (int символ)
                положитьНаСтек интерпретатор строка.Length
                индексТокена <- индексТокена + 1
            | ВстроеннаяФункция(символ) -> 
                let следующийИндекс = 
                    match символ with
                    | 'A' -> 
                        let b = забратьСоСтека интерпретатор
                        let a = забратьСоСтека интерпретатор
                        интерпретатор.стекВычислений.Push (if (a &&& b) <> 0 then 1 else 0)
                        None
                    | 'D' -> 
                        let b = посмотретьНаСтек интерпретатор
                        match b with
                        | Some b ->
                            интерпретатор.стекВычислений.Push b
                        | None -> raise (System.InvalidOperationException("Стек пуст при вызове встроенной функции D"))
                        None
                    | _ ->
                        raise (System.InvalidOperationException("Встроенная функция: " + символ.ToString()))
                индексТокена <- следующийИндекс |> Option.defaultValue (индексТокена + 1)
            | Команда(символ) -> 
                let следующийИндекс = 
                    match символ with
                    // 5.2 Математика
                    | '+' -> 
                        let b = забратьСоСтека интерпретатор
                        let a = забратьСоСтека интерпретатор
                        интерпретатор.стекВычислений.Push (a + b)
                        None
                    | '-' -> 
                        let b = забратьСоСтека интерпретатор
                        let a = забратьСоСтека интерпретатор
                        интерпретатор.стекВычислений.Push (a - b)
                        None
                    | '*' -> 
                        let b = забратьСоСтека интерпретатор
                        let a = забратьСоСтека интерпретатор
                        интерпретатор.стекВычислений.Push (a * b)
                        None
                    | '/' -> 
                        let b = забратьСоСтека интерпретатор
                        let a = забратьСоСтека интерпретатор
                        интерпретатор.стекВычислений.Push (a / b)
                        None
                    | '_' -> 
                        let b = забратьСоСтека интерпретатор
                        let a = забратьСоСтека интерпретатор
                        let результат =
                            if (a > 0 && b > 0) || (a < 0 && b < 0) then
                                a.ToString() + b.ToString() |> int
                            elif (a > 0 && b < 0) || (a > 0 && b < 0) then
                                -(a.ToString() + b.ToString() |> int)
                            else
                                (a * 10 + b)
                        интерпретатор.стекВычислений.Push результат
                        None
                    // 5.3 Логика
                    | '<' ->
                        let b = забратьСоСтека интерпретатор
                        let a = забратьСоСтека интерпретатор
                        интерпретатор.стекВычислений.Push (if a < b then 1 else 0)
                        None
                    | '=' ->
                        let b = забратьСоСтека интерпретатор
                        let a = забратьСоСтека интерпретатор
                        интерпретатор.стекВычислений.Push (if a = b then 1 else 0)
                        None
                    | '>' ->
                        let b = забратьСоСтека интерпретатор
                        let a = забратьСоСтека интерпретатор
                        интерпретатор.стекВычислений.Push (if a > b then 1 else 0)
                        None
                    // 5.4 Печать
                    | '?' -> 
                        let текущееЗначение = посмотретьНаСтек интерпретатор |> Option.defaultValue 0
                        интерпретатор.консоль.Write(текущееЗначение)
                        None
                    | '$' -> 
                        let текущееЗначение = посмотретьНаСтек интерпретатор |> Option.defaultValue 0
                        интерпретатор.консоль.Write(char текущееЗначение)
                        None
                    // 5.5 Стек
                    | ':' -> 
                        if интерпретатор.активныйСтек = 0 then
                            let кодПеременной = интерпретатор.стекИменПеременных.Peek()
                            интерпретатор.переменные.[кодПеременной - int 'a'] <- интерпретатор.стекВычислений.Pop()
                        else
                            let кодПеременной = интерпретатор.стекИменПеременных.Pop()
                            интерпретатор.стекВычислений.Pop() |> игноровать
                            интерпретатор.стекВычислений.Push(интерпретатор.переменные.[кодПеременной - int 'a'])
                        None
                    | ';' -> 
                        if интерпретатор.активныйСтек = 0 then
                            let новыеЗначения = интерпретатор.стекВычислений.ToArray() |> Array.rev
                            новыеЗначения |> Array.iter интерпретатор.стекВычислений.Push
                        else
                            let новыеЗначения = интерпретатор.стекИменПеременных.ToArray() |> Array.rev
                            новыеЗначения |> Array.iter интерпретатор.стекИменПеременных.Push
                        None
                    | '~' -> 
                        интерпретатор.текущееЗначение <- Some (забратьСоСтека интерпретатор)
                        None 
                    | '%' -> 
                        if интерпретатор.активныйСтек = 0 then
                            интерпретатор.стекВычислений.Clear()
                        else
                            интерпретатор.стекИменПеременных.Clear()
                        None 
                    | '#' -> 
                        интерпретатор.активныйСтек <- 1 - интерпретатор.активныйСтек
                        None         
                    // 5.6 Поток управления
                    | '{' -> 
                        let текущееЗначение = посмотретьНаСтек интерпретатор |> Option.defaultValue 0
                        if текущееЗначение = 0 then
                            let mutable счетчик = 0
                            let mutable новыйИндекс = (0, false)
                            for i = индексТокена + 1 to токены.Length do
                                if (not (snd новыйИндекс)) then
                                    let токен = токены[i]
                                    if токен = Команда('}') then
                                        if счетчик = 0 then
                                            новыйИндекс <- (i + 1, true)
                                        else
                                            счетчик <- счетчик - 1
                                    elif токен = Команда('|') then
                                        if счетчик = 0 then
                                            новыйИндекс <- (i + 1, true)
                                            интерпретатор.стекКадров.Push (Условие (индексТокена + 1, false))
                                    elif токен = Команда('{') then
                                        счетчик <- счетчик + 1
                                    else
                                        ()
                            if snd новыйИндекс then
                                Some (fst новыйИндекс)
                            else
                                None
                        else
                            интерпретатор.стекКадров.Push (Условие (индексТокена + 1, true))
                            None
                    | '|' -> 
                        пропуститьКадрУсловия индексТокена
                    | '}' -> 
                        интерпретатор.стекКадров.Pop() |> игноровать
                        None
                    | '^' -> 
                        let mutable кадр = интерпретатор.стекКадров.Peek()
                        let mutable новыйИндекс = (0, false)
                        while not (snd новыйИндекс) do
                            match кадр with
                            | Условие (позиция, _) -> 
                                интерпретатор.стекКадров.Pop() |> игноровать
                                кадр <- интерпретатор.стекКадров.Peek()
                            | Цикл позиция -> 
                                новыйИндекс <- (позиция, true)
                        if snd новыйИндекс then
                            Some (fst новыйИндекс)
                        else
                            None
                    | '\\' -> 
                        let mutable кадр = интерпретатор.стекКадров.Peek()
                        match кадр with
                        | Условие (позиция, _) -> 
                            интерпретатор.стекКадров.Pop() |> игноровать
                            пропуститьКадрУсловия индексТокена
                        | Цикл позиция -> 
                            Some позиция
                    | '!' -> 
                        Some System.Int32.MaxValue
                    // 5.8 Циклы
                    | '[' -> 
                        //интерпретатор.стекЦиклов.Push(int программа.BaseStream.Position)
                        интерпретатор.стекКадров.Push (Цикл (индексТокена + 1))
                        None
                    | ']' -> 
                        let текущееЗначение = посмотретьНаСтек интерпретатор |> Option.defaultValue 0
                        if текущееЗначение = 0 then
                            интерпретатор.стекКадров.Pop() |> игноровать
                            None
                        else
                            let позиция = интерпретатор.стекКадров.Peek()
                            match позиция with
                            | Цикл позиция -> 
                                //интерпретатор.стекЦиклов.Pop() |> игноровать
                            //программа.BaseStream.Seek(int64 позиция, SeekOrigin.Begin) |> игноровать
                                Some позиция
                    | _ ->
                        raise (System.InvalidOperationException("Команда: " + символ.ToString()))
                индексТокена <- следующийИндекс |> Option.defaultValue (индексТокена + 1)
            | Цифра(число) -> 
                интерпретатор.стекВычислений.Push (int число - int '0')
                индексТокена <- индексТокена + 1
            | Символ(символ) -> 
                интерпретатор.стекИменПеременных.Push (int символ)
                индексТокена <- индексТокена + 1

    let интерпретироватьСтроку (интерпретатор: Интерпретатор) (программа: string) =
        интерпретировать интерпретатор (new StreamReader(new MemoryStream(System.Text.Encoding.UTF8.GetBytes(программа))))

    [<EntryPoint>]
    let main argv =
        printfn "Hello from F#"
        0 // return an integer exit code
